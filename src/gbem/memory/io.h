
//Joypad Block
#define GB_JP_REG            0xFF00

//Serial Block
#define GB_SERIAL_START      0xFF01
#define GB_SERIAL_END        0xFF02

//Timer Block
#define GB_TIMER_RANGE_START 0xFF04
#define GB_TIMER_RANGE_END   0xFF07

//Interupt Block
#define GB_IF_REG            0xFF0F

//Audio Block
#define GB_AUDIO_START       0xFF10
#define GB_AUDIO_END         0xFF26
#define GB_WAVE_START        0xFF30
#define GB_WAVE_END          0xFF3F

//PPU Block
#define GB_PPU_START         0xFF40
#define GB_PPU_END           0xFF4B

//BOOTROM
#define GB_BOOT_REG          0xFF50